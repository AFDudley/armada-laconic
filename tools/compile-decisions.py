#!/usr/bin/env python3
"""Compile the architecture-decision log into a current-decisions view.

Reads engineering/09-architecture-decisions.md (the append-only ADR log) and
writes engineering/09a-current-decisions.md: for every accepted ADR, in order,
its title and its live (non-superseded) Decision clauses, followed by a
supersession table. The rules this implements are documented in
engineering/decision-records.md.

Usage:
    tools/compile-decisions.py            # (re)write the compiled view
    tools/compile-decisions.py --check    # verify the log + compiled view; exit 1 on any problem

Stdlib only; deterministic output.
"""

from __future__ import annotations

import re
import sys
from dataclasses import dataclass, field
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "engineering" / "09-architecture-decisions.md"
OUTPUT = ROOT / "engineering" / "09a-current-decisions.md"

SOURCE_REL = "09-architecture-decisions.md"
OUTPUT_REL = "09a-current-decisions.md"

STATUSES = ("proposed", "accepted", "withdrawn")

GENERATED_HEADER = (
    "<!-- GENERATED by tools/compile-decisions.py from "
    f"{SOURCE_REL}. DO NOT EDIT. -->"
)

# A top-level Decision clause: "- **D11.3** (supersedes ...) text"
CLAUSE_RE = re.compile(r"^- \*\*D(\d+)\.(\d+)\*\*(?:\s+(.*))?$")
# Anything that looks like a top-level clause bullet but may be malformed.
CLAUSE_LIKE_RE = re.compile(r"^- \*\*D")
SUPERSEDES_RE = re.compile(r"^\(supersedes\s+([^)]*)\)\s*(.*)$", re.DOTALL)
TARGET_RE = re.compile(r"^D(\d+)\.(\d+)$")
SECTION_RE = re.compile(r"^## ADR-(\d+)\s*$")
INDEX_ROW_RE = re.compile(r"^\|\s*\[(\d+)\]\(#adr-\d+\)\s*\|(.*)\|(.*)\|\s*$")
VERSION_RE = re.compile(r"\bv\d+(?:\.\d+)*\b")


class CompileError(Exception):
    """A structural problem in the decision log."""


@dataclass
class Clause:
    adr: int
    idx: int
    cid: str
    text: str              # clause text with the (supersedes ...) prefix stripped
    raw_lines: list[str]   # full source lines (clause line + indented sub-bullets)
    supersedes: list[str] = field(default_factory=list)
    line_no: int = 0


@dataclass
class Adr:
    num: int
    title: str
    status: str                 # base status token
    version: str | None         # e.g. "v1.5"
    status_line: int
    clauses: list[Clause] = field(default_factory=list)


def _parse_status_cell(cell: str, where: str) -> tuple[str, str | None]:
    """Return (base_status, version_tag) from a '·'-separated status string."""
    base = None
    version = None
    for seg in cell.split("·"):
        seg = seg.strip()
        if seg in STATUSES:
            if base is not None and base != seg:
                raise CompileError(
                    f"{where}: conflicting status tokens '{base}' and '{seg}'"
                )
            base = seg
        m = VERSION_RE.search(seg)
        if m and seg not in STATUSES:
            version = m.group(0)
    if base is None:
        raise CompileError(
            f"{where}: no status in {{{', '.join(STATUSES)}}} found in {cell!r}"
        )
    return base, version


def parse_index(lines: list[str]) -> dict[int, tuple[str, str | None]]:
    """Map ADR number -> (base_status, version) from the Index table."""
    index: dict[int, tuple[str, str | None]] = {}
    in_index = False
    for i, line in enumerate(lines, 1):
        if line.strip() == "## Index":
            in_index = True
            continue
        if in_index and line.startswith("## "):
            break
        if not in_index:
            continue
        m = INDEX_ROW_RE.match(line)
        if not m:
            continue
        num = int(m.group(1))
        status_cell = m.group(3).strip()
        if num in index:
            raise CompileError(f"index: ADR-{num:04d} listed twice")
        index[num] = _parse_status_cell(status_cell, f"index row for ADR-{num:04d}")
    if not index:
        raise CompileError("index: no ADR rows found")
    return index


def parse_adrs(lines: list[str]) -> list[Adr]:
    adrs: list[Adr] = []
    i = 0
    n = len(lines)
    while i < n:
        m = SECTION_RE.match(lines[i])
        if not m:
            i += 1
            continue
        num = int(m.group(1))
        # Status/title line is the next non-empty line.
        j = i + 1
        while j < n and not lines[j].strip():
            j += 1
        if j >= n:
            raise CompileError(f"ADR-{num:04d}: missing title/status line")
        status_line = lines[j]
        title_m = re.match(r"^\*\*(.+?)\*\*\s*·(.*)$", status_line)
        if not title_m:
            raise CompileError(
                f"ADR-{num:04d}: malformed title/status line: {status_line!r}"
            )
        title = title_m.group(1).strip()
        base, version = _parse_status_cell(
            title_m.group(2), f"ADR-{num:04d} status line"
        )
        adr = Adr(num=num, title=title, status=base, version=version, status_line=j + 1)

        # Find the Decision block: from **Decision.** to the next bold section
        # heading / next ## header / EOF.
        k = j + 1
        while k < n and not lines[k].lstrip().startswith("**Decision.**"):
            if SECTION_RE.match(lines[k]):
                break
            k += 1
        if k < n and lines[k].lstrip().startswith("**Decision.**"):
            k += 1
            while k < n:
                line = lines[k]
                if SECTION_RE.match(line):
                    break
                if re.match(r"^\*\*(Consequences|Alternatives|Context)\.\*\*", line):
                    break
                cm = CLAUSE_RE.match(line)
                if cm:
                    cadr, cidx = int(cm.group(1)), int(cm.group(2))
                    body = (cm.group(3) or "").strip()
                    supersedes: list[str] = []
                    sm = SUPERSEDES_RE.match(body)
                    if sm:
                        targets = [t.strip() for t in sm.group(1).split(",")]
                        supersedes = [t for t in targets if t]
                        text = sm.group(2).strip()
                    else:
                        text = body
                    raw = [line.rstrip("\n")]
                    # Gather indented continuation / sub-bullet lines.
                    k2 = k + 1
                    while k2 < n:
                        nxt = lines[k2]
                        if nxt.strip() == "":
                            break
                        if CLAUSE_RE.match(nxt) or CLAUSE_LIKE_RE.match(nxt):
                            break
                        if nxt[:1] in (" ", "\t"):
                            raw.append(nxt.rstrip("\n"))
                            k2 += 1
                            continue
                        break
                    clause = Clause(
                        adr=cadr,
                        idx=cidx,
                        cid=f"D{cadr}.{cidx}",
                        text=text,
                        raw_lines=raw,
                        supersedes=supersedes,
                        line_no=k + 1,
                    )
                    adr.clauses.append(clause)
                    k = k2
                    continue
                if CLAUSE_LIKE_RE.match(line):
                    raise CompileError(
                        f"ADR-{num:04d} line {k + 1}: malformed clause id: "
                        f"{line.strip()!r} (expected '- **D<adr>.<n>** ...')"
                    )
                k += 1
        adrs.append(adr)
        i = k
    if not adrs:
        raise CompileError("no ADR sections found")
    return adrs


def validate(index, adrs) -> tuple[dict, list]:
    """Return (clause_by_id, errors). Raises nothing; collects CompileErrors."""
    errors: list[str] = []
    by_num = {a.num: a for a in adrs}

    # Index <-> body agreement.
    for num in sorted(set(index) | set(by_num)):
        if num not in index:
            errors.append(f"ADR-{num:04d} has a section but no index row")
            continue
        if num not in by_num:
            errors.append(f"ADR-{num:04d} is in the index but has no section")
            continue
        idx_status, idx_ver = index[num]
        adr = by_num[num]
        if (idx_status, idx_ver) != (adr.status, adr.version):
            errors.append(
                f"ADR-{num:04d}: index status '{_fmt_status(idx_status, idx_ver)}' "
                f"disagrees with status line '{_fmt_status(adr.status, adr.version)}'"
            )

    # Clause IDs: well-formed, matching ADR, sequential, unique.
    clause_by_id: dict[str, Clause] = {}
    for adr in adrs:
        seen: set[str] = set()
        expected = 1
        for c in adr.clauses:
            if c.adr != adr.num:
                errors.append(
                    f"ADR-{adr.num:04d} line {c.line_no}: clause {c.cid} has the "
                    f"wrong ADR number (expected D{adr.num}.x)"
                )
            if c.cid in seen:
                errors.append(
                    f"ADR-{adr.num:04d} line {c.line_no}: duplicate clause id {c.cid}"
                )
            seen.add(c.cid)
            if c.adr == adr.num and c.idx != expected:
                errors.append(
                    f"ADR-{adr.num:04d} line {c.line_no}: clause {c.cid} out of "
                    f"sequence (expected D{adr.num}.{expected})"
                )
            expected = c.idx + 1 if c.adr == adr.num else expected
            if c.cid not in clause_by_id:
                clause_by_id[c.cid] = c

    # Supersession targets.
    #   target -> list[(superseding_clause, superseding_adr_status)]
    superseders: dict[str, list[tuple[Clause, str]]] = {}
    for adr in adrs:
        for c in adr.clauses:
            for tgt in c.supersedes:
                tm = TARGET_RE.match(tgt)
                if not tm:
                    errors.append(
                        f"{c.cid}: malformed supersede target {tgt!r}"
                    )
                    continue
                if tgt not in clause_by_id:
                    errors.append(
                        f"{c.cid}: supersede target {tgt} does not exist"
                    )
                    continue
                tgt_adr = int(tm.group(1))
                if tgt_adr >= adr.num:
                    errors.append(
                        f"{c.cid}: supersede target {tgt} is not in an earlier ADR "
                        f"(ADR-{tgt_adr:04d} is not before ADR-{adr.num:04d})"
                    )
                    continue
                superseders.setdefault(tgt, []).append((c, adr.status))

    # A clause superseded more than once by accepted ADRs is a conflict.
    for tgt, lst in superseders.items():
        accepted = [c for c, st in lst if st == "accepted"]
        if len(accepted) > 1:
            who = ", ".join(sorted(c.cid for c in accepted))
            errors.append(
                f"{tgt} is superseded by more than one accepted ADR: {who}"
            )

    return clause_by_id, superseders, errors


def _fmt_status(base: str, version: str | None) -> str:
    return base if not version else f"{base} · {version}"


def _superseded_by_accepted(cid: str, superseders) -> list[Clause]:
    return [c for c, st in superseders.get(cid, []) if st == "accepted"]


def render(index, adrs, clause_by_id, superseders) -> str:
    out: list[str] = []
    out.append(GENERATED_HEADER)
    out.append("")
    out.append("# 9a. Current Decisions")
    out.append("")
    out.append(
        f"Generated from [9. Architecture Decisions](./{SOURCE_REL}) by "
        "`tools/compile-decisions.py` — do not edit by hand. The rules this page "
        "follows are in [decision-records.md](./decision-records.md)."
    )
    out.append("")
    out.append(
        "The live (non-superseded) Decision clauses of every accepted ADR, in "
        "order, followed by the supersession table. Only accepted ADRs contribute "
        "live clauses, and only their supersessions apply."
    )
    out.append("")
    out.append("## Live decisions")
    out.append("")

    accepted = [a for a in adrs if a.status == "accepted"]
    any_live = False
    for adr in accepted:
        live = [
            c for c in adr.clauses
            if not _superseded_by_accepted(c.cid, superseders)
        ]
        if not live:
            continue
        any_live = True
        out.append(f"### ADR-{adr.num:04d} — {adr.title}")
        for c in live:
            out.extend(c.raw_lines)
        out.append("")
    if not any_live:
        out.append("_No live decisions._")
        out.append("")

    # Supersession table (by accepted ADRs).
    out.append("## Supersessions")
    out.append("")
    rows = []
    for tgt in sorted(superseders, key=_cid_sort_key):
        for c in sorted(_superseded_by_accepted(tgt, superseders), key=lambda x: _cid_sort_key(x.cid)):
            tgt_clause = clause_by_id.get(tgt)
            tgt_text = _flatten(tgt_clause) if tgt_clause else "(unknown)"
            rows.append((tgt, c.cid, tgt_text))
    if rows:
        out.append("| Superseded | By | Superseded decision (for reference) |")
        out.append("|---|---|---|")
        for tgt, by, text in rows:
            out.append(f"| {tgt} | {by} | {_cell(text)} |")
    else:
        out.append("_None._")
    out.append("")

    # Pending supersessions (declared only by not-yet-accepted ADRs).
    pending_rows = []
    for tgt in sorted(superseders, key=_cid_sort_key):
        if _superseded_by_accepted(tgt, superseders):
            continue
        for c, st in sorted(superseders[tgt], key=lambda x: _cid_sort_key(x[0].cid)):
            pending_rows.append((tgt, c.cid, st))
    if pending_rows:
        out.append("## Pending supersessions")
        out.append("")
        out.append(
            "Declared by not-yet-accepted ADRs; they do not apply until the ADR is "
            "accepted, so the targets above are still live."
        )
        out.append("")
        out.append("| Would supersede | By | ADR status |")
        out.append("|---|---|---|")
        for tgt, by, st in pending_rows:
            out.append(f"| {tgt} | {by} | {st} |")
        out.append("")

    return "\n".join(out).rstrip("\n") + "\n"


def _flatten(clause: Clause) -> str:
    parts = [clause.text]
    for extra in clause.raw_lines[1:]:
        parts.append(extra.strip().lstrip("- ").strip())
    return " ".join(p for p in parts if p)


def _cell(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ").strip()


def _cid_sort_key(cid: str):
    m = TARGET_RE.match(cid)
    return (int(m.group(1)), int(m.group(2))) if m else (10**9, cid)


def main(argv: list[str]) -> int:
    check = "--check" in argv[1:]
    unknown = [a for a in argv[1:] if a != "--check"]
    if unknown:
        print(f"compile-decisions.py: unknown arguments: {' '.join(unknown)}", file=sys.stderr)
        return 2

    try:
        text = SOURCE.read_text(encoding="utf-8")
    except OSError as e:
        print(f"compile-decisions.py: cannot read {SOURCE}: {e}", file=sys.stderr)
        return 2
    lines = text.splitlines()

    try:
        index = parse_index(lines)
        adrs = parse_adrs(lines)
        clause_by_id, superseders, errors = validate(index, adrs)
    except CompileError as e:
        print(f"compile-decisions.py: {e}", file=sys.stderr)
        return 1

    if errors:
        for e in errors:
            print(f"compile-decisions.py: {e}", file=sys.stderr)
        return 1

    compiled = render(index, adrs, clause_by_id, superseders)

    if check:
        try:
            existing = OUTPUT.read_text(encoding="utf-8")
        except OSError:
            existing = None
        if existing != compiled:
            print(
                f"compile-decisions.py: {OUTPUT_REL} is stale; "
                "run tools/compile-decisions.py to regenerate it.",
                file=sys.stderr,
            )
            return 1
        return 0

    OUTPUT.write_text(compiled, encoding="utf-8")
    print(f"compile-decisions.py: wrote {OUTPUT_REL}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
